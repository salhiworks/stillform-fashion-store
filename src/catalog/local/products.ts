import type { Colorway, Product, Variant } from "../types";

// Demo catalogue for the Phase 1 prototype. Prices are in cents.

/** Editorial photographs for a colourway, by name in the editorial manifest. */
interface Editorial {
  lifestyle?: string[];
  details?: string[];
}

function colorway(product: string, id: string, name: string, swatch: string, editorial: Editorial = {}): Colorway {
  const ref = (view: string) => `${product}/${id}/${view}`;
  const photo = (names: string[] = []) => names.map((file) => `editorial/${file}`);
  return {
    id,
    name,
    swatch,
    media: { front: ref("front"), back: ref("back"), side: ref("side"), gallery: [], lifestyle: photo(editorial.lifestyle), details: photo(editorial.details) },
  };
}

/** Builds the variant grid from a stock count per size, in the product's size order. */
function stock(product: string, colorwayId: string, sizes: string[], counts: number[]): Variant[] {
  return sizes.map((size, i) => ({ sku: `${product}-${colorwayId}-${size}`.toUpperCase(), colorwayId, size, stock: counts[i] ?? 0 }));
}

